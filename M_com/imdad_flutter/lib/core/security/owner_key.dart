///
/// هذا هو جوهر الحماية: رموز تفعيل الأجهزة يجب أن يوقّعها المالك وحده. لو قُرئ
/// المفتاح العام من قاعدة البيانات لاستطاع من يثبّت نسخة جديدة أن يولّد مفتاحه
/// الخاص، ويضع عامَّه في قاعدته، ويصدر لنفسه رمزًا — فيصير هو الإدارة.
///
/// بدفنه هنا: لا يُقبل إلا رمز موقَّع بالمفتاح الخاص المقابل، وهو عندك وحدك.
///
/// ─────────────────────────────────────────────────────────────
/// **كيف تولّد مفتاحك (مرة واحدة فقط):**
///
/// ```bash
/// dart run tool/make_owner_key.dart
/// ```
///
/// يطبع الأمر المفتاح العام — انسخه إلى [publicKey] أدناه — ويحفظ المفتاح
/// **الخاص** في ملف خارج المستودع. احفظه كما تحفظ مفتاح توقيع الإصدار:
/// ضياعه يعني أنك لن تستطيع تفعيل أي جهاز جديد بعد اليوم.
///
/// ثم أعد بناء التطبيق. النسخ المبنية قبل ذلك لا تقبل مفتاحك الجديد.
/// ─────────────────────────────────────────────────────────────
class OwnerKey {
  const OwnerKey._();

  /// المفتاح العام (نقطة P-256 مضغوطة، Base64).
  ///
  /// فارغ = **وضع التطوير**: التفعيل معطّل والتطبيق يعمل بلا قيد. لا تبنِ نسخة
  /// للتوزيع وهو فارغ — راجع [isConfigured].
  static const String publicKey = 'AnRmvLzALYIwbE6reNLuKhNvFHYZcj5ANcPh8txRwr4z';

  /// هل ضُبط مفتاح مالك؟ حين لا يُضبط يبقى التطبيق مفتوحًا للتطوير والاختبار.
  static bool get isConfigured => publicKey.isNotEmpty;
}
